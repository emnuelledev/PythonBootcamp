# Here a few examples with the modulo operator in Python:

print(10 % 3)  # Output: 1
print(15 % 4)  # Output: 3
print(20 % 5)  # Output: 0

# Checking if a number is even or odd using the modulo operator
number = int(input("Enter a number: "))

if number % 2 == 0:
    print(f"{number} is even.") # PAR
else:
    print(f"{number} is odd.") # ÍMPAR
    
    